export type ScienceExam = "TYT" | "AYT";

export interface ScienceCard {
  id: string;
  subject: ScienceSubject;
  exams: ScienceExam[];
  topic: string;
  icon: string;
  title: string;
  question: string;
  answer: string;
  cue: string;
  mistake: string;
  tip: string;
}

type CardRow = [string, ScienceExam[], string, string, string, string, string, string, string, string];
function cards(subject: ScienceSubject, rows: CardRow[]): ScienceCard[] {
  return rows.map(([id, exams, topic, icon, title, question, answer, cue, mistake, tip]) =>
    ({id, subject, exams, topic, icon, title, question, answer, cue, mistake, tip}));
}

